def run_local_scan(packet_count):
    from scanner.sniffer import start_sniffing, captured_packets
    captured_packets.clear()
    with st.spinner(f"Scanning network... capturing {packet_count} packets"):
        start_sniffing(packet_count=packet_count)
    return captured_packets


def run_website_scan(packet_count, sites, timeout_seconds=15):
    from scanner.sniffer import start_sniffing, captured_packets

    normalized_sites = [site.strip() for site in sites if site.strip()]
    if not normalized_sites:
        raise ValueError("Enter at least one website URL or domain to scan.")

    captured_packets.clear()
    with st.spinner(f"Scanning website traffic for {', '.join(normalized_sites)}"):
        start_sniffing(
            packet_count=packet_count,
            sites=normalized_sites,
            timeout=timeout_seconds,
        )
    return captured_packets


