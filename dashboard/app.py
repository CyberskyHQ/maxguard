def parse_voice_command(command: str) -> str | None:
    """Map natural voice commands to supported scan actions."""
    if not command:
        return None

    normalized = command.lower().strip()
    website_keywords = ("website", "web", "site", "url")
    scan_keywords = ("scan", "start", "run", "begin", "go", "check", "analyze")

    if any(keyword in normalized for keyword in website_keywords) and any(
        keyword in normalized for keyword in scan_keywords
    ):
        return "website_scan"

    if any(keyword in normalized for keyword in scan_keywords):
        return "live_scan"

    return None


def build_voice_briefing(result: dict, packets: list[dict] | None, mode: str) -> str:
    """Build the spoken briefing text for the selected voice mode."""
    packets = packets or []
    severity = result.get("severity", {})
    threat_level = result.get("threat_level", "UNKNOWN")
    total_packets = result.get("total_packets", len(packets))
    total_violations = result.get("total_violations", 0)
    affected_devices = result.get("affected_devices", [])
    top_device = affected_devices[0] if affected_devices else None
    requested_sites = sorted(
        {
            packet.get("requested_site")
            for packet in packets
            if packet.get("requested_site")
        }
    )
    violation_types = result.get("violation_types", [])
    analysis = result.get("analysis", "No analysis available.")
    has_targeted_sites = bool(requested_sites)

    if has_targeted_sites:
        intro = "I’ve reviewed the latest website scan."
    else:
        intro = "I’ve reviewed the latest network scan."

    if mode == "Executive":
        return (
            f"{intro} Here’s the quick executive update. Threat level is {threat_level}. "
            f"We reviewed {total_packets} packets and found {total_violations} potential PCI related violations. "
            "The main takeaway is that this environment should be reviewed before it is treated as fully clean."
        )

    if mode == "Technical":
        return (
            f"{intro} Here’s the technical summary. Threat level is {threat_level}, with a severity score of "
            f"{severity.get('overall_score', 0)} out of 10. "
            f"We found {total_violations} violations across {total_packets} captured packets. "
            f"Top violation types include {', '.join(violation_types[:3]) if violation_types else 'none detected'}."
        )

    if mode == "Remediation":
        if top_device:
            return (
                f"{intro} Here’s the remediation priority. Start with device {top_device['ip']}, "
                f"which shows {top_device['violation_count']} violations. "
                "First review any insecure services, confirm whether the exposure is expected, and then work through the fix steps shown in the dashboard."
            )
        return (
            f"{intro} Here’s the remediation summary. Review the investigation guides, validate any insecure protocols, "
            "and prioritize the highest severity findings first."
        )

    if mode == "Website Scan":
        site_text = ", ".join(requested_sites) if requested_sites else "the selected websites"
        return (
            f"I’ve got the website scan results for {site_text}. "
            f"The system captured {total_packets} packets and found {total_violations} possible compliance issues. "
            "This gives us a focused view of the traffic generated by those specific web destinations."
        )

    first_paragraph = analysis.split("\n\n")[0].strip()
    if first_paragraph:
        return f"{intro} {first_paragraph}"
    return f"{intro} I have the analysis ready."


def infer_scan_type(packets: list[dict] | None) -> str:
    packets = packets or []
    if any(packet.get("requested_site") for packet in packets):
        return "Website Scan"
    return "Network Scan"


def build_risk_recommendation(result: dict, packets: list[dict] | None) -> str:
    packets = packets or []
    severity = result.get("severity", {})
    affected_devices = result.get("affected_devices", [])
    requested_sites = sorted(
        {
            packet.get("requested_site")
            for packet in packets
            if packet.get("requested_site")
        }
    )

    if severity.get("overall_score", 0) >= 8 and affected_devices:
        return (
            f"Prioritize immediate review of device {affected_devices[0]['ip']} and isolate any insecure services "
            "before the next validation cycle."
        )

    if requested_sites and result.get("total_violations", 0) > 0:
        return (
            "Re-run the targeted website scan after validating outbound traffic paths and confirm whether the flagged "
            "destinations are expected business activity."
        )

    if result.get("total_violations", 0) > 0:
        return "Review the investigation guides, validate the flagged protocols, and remediate the highest severity findings first."

    return "No urgent issues were detected. Document the clean result and keep scheduled scans running for continued assurance."

